/// 动作示范 GIF；没有或抽检不符时返回 null。
String? getExerciseGif(String exerciseId) {
  if (kMismatchedGifIds.contains(exerciseId)) return null;
  final name = kExerciseGifs[exerciseId];
  return name == null ? null : 'assets/images/$name';
}

/// 列表用静态缩略图；没有或抽检不符时返回 null。
String? getExerciseThumb(String exerciseId) {
  if (kMismatchedGifIds.contains(exerciseId)) return null;
  if (!kExerciseThumbIds.contains(exerciseId)) return null;
  return 'assets/images/thumbs/$exerciseId.png';
}

/// 兼容旧调用：优先 GIF。
String? getExerciseImage(String exerciseId, {bool preferGif = true}) {
  if (preferGif) return getExerciseGif(exerciseId) ?? getExerciseThumb(exerciseId);
  return getExerciseThumb(exerciseId) ?? getExerciseGif(exerciseId);
}
